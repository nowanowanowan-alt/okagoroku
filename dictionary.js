/* =========================================================
   DOM取得
========================================================= */

const searchInput =
    document.getElementById("searchInput");

const searchButton =
    document.getElementById("searchButton");

const typeFilter =
    document.getElementById("typeFilter");

const gradeFilter =
    document.getElementById("gradeFilter");

const weekFilter =
    document.getElementById("weekFilter");

const resetButton =
    document.getElementById("resetButton");

const resultList =
    document.getElementById("resultList");

const resultCount =
    document.getElementById("resultCount");



/* =========================================================
   週の選択肢を作る
========================================================= */

for (let week = 1; week <= 43; week++) {

    const option =
        document.createElement("option");

    option.value = week;

    option.textContent =
        `第${week}週`;

    weekFilter.appendChild(option);
}



/* =========================================================
   辞書検索
========================================================= */

function searchDictionary() {

    // 検索文字列
    const keyword =
        searchInput.value
            .trim()
            .toLowerCase();


    // 現在のフィルター
    const selectedType =
        typeFilter.value;

    const selectedGrade =
        gradeFilter.value;

    const selectedWeek =
        weekFilter.value;


    const results =
        dictionary.filter(item => {


            /* -------------------------
               文字検索
            ------------------------- */

            const searchableText = [

                item.word,

                item.meaning,

                item.example,

                item.note

            ]
                .join(" ")
                .toLowerCase();


            const matchesKeyword =
                keyword === "" ||
                searchableText.includes(keyword);



            /* -------------------------
               OK / TRT
            ------------------------- */

            const matchesType =
                selectedType === "all" ||
                item.tags.type === selectedType;



            /* -------------------------
               学年
            ------------------------- */

            const matchesGrade =
                selectedGrade === "all" ||
                item.tags.grade === selectedGrade;



            /* -------------------------
               週
            ------------------------- */

            const matchesWeek =
                selectedWeek === "all" ||
                String(item.tags.week) === selectedWeek;



            /* -------------------------
               全条件を満たしたものだけ
            ------------------------- */

            return (
                matchesKeyword &&
                matchesType &&
                matchesGrade &&
                matchesWeek
            );

        });


    displayResults(results);
}



/* =========================================================
   検索結果表示
========================================================= */

function displayResults(results) {

    resultList.innerHTML = "";


    resultCount.textContent =
        `${results.length}件`;


    /* -------------------------
       該当なし
    ------------------------- */

    if (results.length === 0) {

        resultList.innerHTML = `

            <div class="no-result">

                該当する単語がありません。

            </div>

        `;

        return;
    }



    /* -------------------------
       単語カード作成
    ------------------------- */

    results.forEach(item => {


        const card =
            document.createElement("div");

        card.className =
            "word-card";


        card.innerHTML = `

            <!-- 単語 -->

            <div class="word-title">

                <span class="word">
                    ${item.word}
                </span>

            </div>


            <!-- タグ -->

            <div class="tags">

                <span class="tag">
                    ${item.tags.type}
                </span>

                <span class="tag">
                    ${item.tags.grade}
                </span>

                <span class="tag">
                    第${item.tags.week}週
                </span>

            </div>


            <!-- 意味 -->

            <div class="dictionary-item">

                <div class="dictionary-label">
                    意味
                </div>

                <div class="dictionary-content">
                    ${item.meaning}
                </div>

            </div>


            <!-- 用例 -->

            <div class="dictionary-item">

                <div class="dictionary-label">
                    用例
                </div>

                <div class="dictionary-content example-content">
                    ${item.example}
                </div>

            </div>


            <!-- 備考 -->

            <div class="dictionary-item">

                <div class="dictionary-label">
                    備考
                </div>

                <div class="dictionary-content note-content">
                    ${item.note}
                </div>

            </div>

        `;


        resultList.appendChild(card);

    });

}



/* =========================================================
   イベント
========================================================= */


/* 検索ボタン */

searchButton.addEventListener(
    "click",
    searchDictionary
);



/* Enterキー */

searchInput.addEventListener(
    "keydown",
    event => {

        if (event.key === "Enter") {

            searchDictionary();

        }

    }
);



/* フィルター変更 */

typeFilter.addEventListener(
    "change",
    searchDictionary
);


gradeFilter.addEventListener(
    "change",
    searchDictionary
);


weekFilter.addEventListener(
    "change",
    searchDictionary
);



/* =========================================================
   リセット
========================================================= */

resetButton.addEventListener(
    "click",
    () => {

        searchInput.value = "";

        typeFilter.value = "all";

        gradeFilter.value = "all";

        weekFilter.value = "all";

        searchDictionary();

    }
);



/* =========================================================
   初期表示
========================================================= */

displayResults(dictionary);
