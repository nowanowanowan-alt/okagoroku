function sortResults(results) {

    const sortType = sortSelect.value;

    if (sortType === "default") {
        return;
    }


    // 50音順
    if (sortType === "kana") {

        results.sort(function (a, b) {

            return (a.reading || "").localeCompare(
                b.reading || "",
                "ja"
            );

        });

    }


    // 50音逆順
    if (sortType === "kana-reverse") {

        results.sort(function (a, b) {

            return (b.reading || "").localeCompare(
                a.reading || "",
                "ja"
            );

        });

    }


    // 学年の順番
    const gradeOrder = {
        "中1": 1,
        "中2": 2,
        "中3": 3,
        "高1": 4,
        "高2": 5,
        "高3": 6
    };


    // 学年が早い順
    if (sortType === "grade") {

        results.sort(function (a, b) {

            return (
                (gradeOrder[a.grade] || 99) -
                (gradeOrder[b.grade] || 99)
            );

        });

    }


    // 学年が遅い順
    if (sortType === "grade-reverse") {

        results.sort(function (a, b) {

            return (
                (gradeOrder[b.grade] || 99) -
                (gradeOrder[a.grade] || 99)
            );

        });

    }


    // 週が早い順
    if (sortType === "week") {

        results.sort(function (a, b) {

            const weekA =
                parseInt(a.week, 10) || 999;

            const weekB =
                parseInt(b.week, 10) || 999;

            return weekA - weekB;

        });

    }


    // 週が遅い順
    if (sortType === "week-reverse") {

        results.sort(function (a, b) {

            const weekA =
                parseInt(a.week, 10) || -1;

            const weekB =
                parseInt(b.week, 10) || -1;

            return weekB - weekA;

        });

    }

}


